"""The zip a person downloads: a Power BI project, this dataset's CSVs, and a README.

This is the whole Phase 9 delivery surface. Power BI Desktop is the only Power BI product involved --
nothing here talks to the Power BI Service, which needs a tenant and licensing the project doesn't
have. The export is therefore a file, not an integration, and the platform's own React dashboards
remain the in-product rendering path.

It is also the one route that hands out raw rows in bulk, which is why the router gates it at Analyst
and audit-logs it: every other read path returns aggregates the engine computed, with caveats,
truncation flags and number-grounding checks attached. None of those survive a download.
"""
import io
import zipfile
from pathlib import Path

from insightflow_core.models.semantic_model import SemanticModel
from insightflow_core.registry import MetricRegistry

from insightflow_backend.powerbi import tmdl
from insightflow_backend.powerbi.build import build_bi_model
from insightflow_backend.powerbi.ir import BIModel

# What the DataFolder parameter says before the reader edits it. A path, not an empty string, so the
# shape of the thing they have to supply is obvious in the parameter dialog.
DEFAULT_DATA_FOLDER = "C:\\InsightFlow\\data\\"


def safe_name(name: str) -> str:
    """A project name safe as a file and folder name. Dataset names come from upload filenames."""
    cleaned = "".join(c if c.isalnum() or c in " -_" else "_" for c in name).strip()
    return cleaned or "InsightFlow"


def _readme(model: BIModel, project: str) -> str:
    lines = [
        f"# {project} — Power BI export",
        "",
        "Generated by InsightFlow from this project's semantic model. Everything here is derived",
        "from mappings that passed review; unreviewed and rejected mappings are not included.",
        "",
        "## Opening it",
        "",
        f"1. Unzip the whole folder, keeping `data/` next to `{project}.pbip`.",
        f"2. Open `{project}.pbip` in Power BI Desktop.",
        "3. Home → Transform data → Manage parameters → set **DataFolder** to the full path of the",
        "   unzipped `data` folder, ending with a backslash. Then Close & Apply.",
        "",
        "Power Query has no way to find the folder a project was opened from, so this one step",
        "cannot be baked in.",
        "",
        "## What's in the model",
        "",
        f"- {len(model.tables)} table(s), loaded from the CSVs in `data/`.",
        f"- {len(model.relationships)} relationship(s), with cardinality measured from the data.",
        f"- {len(model.measures)} measure(s), generated from InsightFlow's metric registry.",
    ]
    if model.date_table:
        lines.append(
            f"- A `{model.date_table.table_name}` table covering {model.date_table.start_date} to "
            f"{model.date_table.end_date} — this dataset's own date range, not today's date."
        )
    lines += ["", "### Columns", "", "Columns keep their original names from your files. A column's"]
    lines.append("description shows what InsightFlow mapped it to and how confident it was.")

    inactive = [r for r in model.relationships if not r.is_active]
    if inactive:
        lines += ["", "### Relationships left inactive", ""]
        lines.append("Power BI allows only one active path between two tables. These were detected but")
        lines.append("deactivated so the active ones form a single unambiguous path:")
        lines.append("")
        for relationship in inactive:
            lines.append(
                f"- `{relationship.from_table}[{relationship.from_column}]` → "
                f"`{relationship.to_table}[{relationship.to_column}]` — {relationship.inactive_reason}"
            )

    if model.omitted_metrics:
        lines += ["", "### Metrics not exported", ""]
        lines.append("These are in InsightFlow's registry but can't be expressed against this dataset:")
        lines.append("")
        for name, reason in model.omitted_metrics:
            lines.append(f"- **{name}** — {reason}")

    lines += [
        "",
        "## What this export does not carry",
        "",
        "Numbers here are recomputed by Power BI in DAX, from the same measure definitions",
        "InsightFlow uses — not copied from InsightFlow's results. That means the protections the",
        "platform applies around a number stay behind:",
        "",
        "- **Caveats.** InsightFlow flags a number that is correct but misleading; a measure in",
        "  Desktop shows no warning. Where a caveat can apply, its condition is written into the",
        "  measure's description — a note, not a guardrail.",
        "- **Row-cap warnings.** InsightFlow marks a grouped result that was cut off. Power BI loads",
        "  every row instead, so this doesn't apply here — but it also means the file holds your full",
        "  data, not an aggregate.",
        "- **Access control.** Once this file is on a disk, InsightFlow's project roles no longer",
        "  apply to it.",
        "- **Slicer semantics.** A ratio measure under a slicer is computed the Power BI way (filters",
        "  propagate through relationships), which can differ from InsightFlow's answer for the same",
        "  question. Unfiltered, they agree.",
    ]
    return "\n".join(lines) + "\n"


def _project_files(model: BIModel, project: str) -> dict[str, str]:
    """Every text file of the PBIP project, keyed by its path inside the zip."""
    semantic_dir = f"{project}.SemanticModel"
    report_dir = f"{project}.Report"
    definition = f"{semantic_dir}/definition"

    relationships = list(model.relationships)
    calendar_relationship = tmdl.calendar_relationship(model)
    if calendar_relationship:
        relationships.append(calendar_relationship)

    files = {
        f"{project}.pbip": tmdl.pbip_json(project),
        f"{semantic_dir}/.platform": tmdl.platform_json(project, "SemanticModel"),
        f"{semantic_dir}/definition.pbism": tmdl.pbism_json(),
        f"{definition}/database.tmdl": tmdl.database_tmdl(),
        f"{definition}/model.tmdl": tmdl.model_tmdl(model),
        f"{definition}/expressions.tmdl": tmdl.expressions_tmdl(DEFAULT_DATA_FOLDER),
        f"{definition}/relationships.tmdl": tmdl.relationships_tmdl(relationships),
        f"{report_dir}/.platform": tmdl.platform_json(project, "Report"),
        f"{report_dir}/definition.pbir": tmdl.pbir_json(project),
        f"{report_dir}/report.json": tmdl.report_json(),
        "README.md": _readme(model, project),
    }

    for table in model.tables:
        measures = [m for m in model.measures if m.home_table == table.name]
        link_column = None
        source_column = None
        if model.date_table and model.date_table.related_table == table.name:
            link_column = tmdl.date_link_column_name()
            source_column = model.date_table.related_column
        files[f"{definition}/tables/{table.name}.tmdl"] = tmdl.table_tmdl(
            table, measures, table.delimiter, link_column, source_column
        )

    if model.date_table:
        files[f"{definition}/tables/{model.date_table.table_name}.tmdl"] = tmdl.calendar_tmdl(model.date_table)

    return files


def build_export_zip(
    name: str, semantic_model: SemanticModel, registry: MetricRegistry, data_dir: Path
) -> bytes:
    """`semantic_model` is trusted here, not by the caller, so no route can accidentally export an
    unreviewed mapping. Same rule as PipelineCache._computable_model: anything that computes numbers
    is built on `.trusted()`, and a DAX measure computes numbers."""
    trusted = semantic_model.trusted()
    project = safe_name(name)
    model = build_bi_model(project, trusted, registry, data_dir)

    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for path, content in _project_files(model, project).items():
            archive.writestr(path, content)
        for table in model.tables:
            csv_path = data_dir / f"{table.source_file}.csv"
            if csv_path.exists():
                archive.write(csv_path, f"data/{table.source_file}.csv")
    return buffer.getvalue()
